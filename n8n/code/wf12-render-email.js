// Renders the report. Tables and the disclosure footer come from code; the
// model's narrative is used only if it passed the compliance gate.
const DISCLOSURE_VERSION = '2026.09';
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const md = (s) => esc(s)
  .split(/\n{2,}/)
  .map((p) => (/^\s*[-*] /m.test(p)
    ? `<ul>${p.split('\n').filter((l) => l.trim()).map((l) => `<li>${l.replace(/^\s*[-*] /, '')}</li>`).join('')}</ul>`
    : `<p>${p.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>').replace(/\n/g, '<br>')}</p>`))
  .join('');
const usd = (x) => (x === null || x === undefined ? 'n/a' : `USD ${Number(x).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`);

return $input.all().map(({ json: r }) => {
  const accounts = r.metrics?.accounts ?? [];
  const breakers = r.metrics?.breaker_events ?? [];
  const rows = accounts.map((a) => `<tr><td>${esc(a.account_id)}</td><td>${esc(a.venue)}</td><td>${usd(a.equity_usd)}</td>`
    + `<td>${usd(a.day_change_usd)}</td><td>${usd(a.fees_usd)}</td><td>${usd(a.funding_usd)}</td><td>${esc(a.risk_mode)}</td></tr>`).join('');
  const narrative = r.compliance?.pass && r.draft
    ? md(r.draft.summary_md)
    : '<p>Your daily account summary is below. Figures come directly from your connected exchange accounts.</p>';
  const breakerList = breakers.length
    ? `<p><strong>Risk controls that acted:</strong></p><ul>${breakers.map((b) => `<li>${esc(b.ts)} ${esc(b.tier)} ${esc(b.metric ?? '')} ${esc(b.action ?? '')}</li>`).join('')}</ul>`
    : '';
  const subject = r.compliance?.pass && r.draft?.subject ? r.draft.subject : `Your AQOS account summary for ${r.period}`;
  const html = [
    `<p>Account summary for ${esc(r.period)} (UTC). Mode: ${esc(r.metrics?.mode ?? '')}.</p>`,
    narrative,
    '<table cellpadding="6" style="border-collapse:collapse" border="1"><tr><th>Account</th><th>Venue</th><th>Equity</th>'
      + `<th>Day change</th><th>Fees</th><th>Funding</th><th>Risk mode</th></tr>${rows}</table>`,
    breakerList,
    `<p style="font-size:12px;color:#555">This report is generated by software from data in exchange accounts you control. `
      + 'It is not investment advice or a recommendation. Past results do not indicate future results. Digital assets are volatile '
      + `and you can lose all capital allocated to trading. Disclosures v${DISCLOSURE_VERSION}.</p>`,
  ].join('\n');
  return { json: { ...r, to: r.email, subject: subject.slice(0, 90), html, hash_input: `${r.client_id}|${r.period}|${html}` } };
});
