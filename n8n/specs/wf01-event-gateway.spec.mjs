// WF-01 Event gateway: the stream gateway and the EMS push signed events here.
// HMAC over the raw body, 30 s replay window, event_id de-duplication in SQL.
// Routes: bar_close -> signal cycle, market_stress -> risk monitor,
// execution_events -> settlement, feed_status -> data-quality rules + LLM triage.
import { workflow, webhook, hmacOfRawBody, code, pgFn, ifNode, switchNode, cond, respond, execWf, http, claude, noop } from '../../tools/lib/dsl.mjs';

export default workflow({
  id: 'AQOS01EventGatew',
  name: 'AQOS-01 Event gateway',
  active: true,
  settings: { executionTimeout: 120, saveDataSuccessExecution: 'none' },
  nodes: [
    webhook('Gateway events', { path: 'aqos/events', auth: 'none', rawBody: true, respond: 'responseNode', note: 'Authenticated by HMAC over the raw body (header x-aqos-signature), not by a bearer token.' }),
    hmacOfRawBody('Compute HMAC'),
    code('Verify signature', 'common-verify-signed-webhook.js'),
    ifNode('Signature valid?', [cond('={{ $json.valid }}', 'boolean:true')]),
    pgFn('Dead-letter bad request', 'ops.dead_letter_put', {
      payload: "{ source: 'event_gateway', reason: $json.reason, payload: { source_ip: $json.source_ip } }",
    }),
    respond('Reject 401', { code: 401, body: { ok: false, error: 'unauthorized' } }),
    pgFn('Ingest event', 'ops.ingest_event', { payload: '$json.envelope' }),
    respond('Acknowledge', { code: 200, body: '={{ { ok: true, inserted: $json.r.inserted, event_id: $json.r.event_id } }}' }),
    ifNode('First delivery?', [cond('={{ $json.r.inserted }}', 'boolean:true')]),
    switchNode('Route by type', [
      { key: 'bar_close', conds: [cond('={{ $json.r.type }}', 'string:equals', 'bar_close')] },
      { key: 'market_stress', conds: [cond('={{ $json.r.type }}', 'string:equals', 'market_stress')] },
      { key: 'execution_events', conds: [cond('={{ $json.r.type }}', 'string:equals', 'execution_events')] },
      { key: 'feed_status', conds: [cond('={{ $json.r.type }}', 'string:equals', 'feed_status')] },
    ], { fallback: 'other' }),
    execWf('Run signal cycle', 'AQOS03SignalCycl', { wait: false }),
    execWf('Run risk monitor', 'AQOS07RiskMonitr', { wait: false }),
    execWf('Run settlement', 'AQOS06Settlement', { wait: false }),
    noop('Other event stored', 'Unrouted types are kept in ops.events for audit'),
    code('Feed rules', 'wf01-feed-rules.js'),
    ifNode('Quarantine?', [cond('={{ $json.action }}', 'string:equals', 'quarantine')]),
    pgFn('Quarantine feed', 'md.quarantine_feed', { payload: "{ feed_id: $json.feed_id, reason: $json.reason, actor: 'data_quality' }" }),
    ifNode('Needs triage?', [cond('={{ $json.triage }}', 'boolean:true')]),
    code('Build DQ triage request', 'wf01-dq-triage-request.js'),
    claude('Claude DQ triage', { timeoutMs: 90000 }),
    code('DQ triage result', 'wf01-dq-triage-result.js'),
    ifNode('Backfill?', [cond('={{ $json.backfill }}', 'object:notEmpty')]),
    http('Request backfill', {
      method: 'POST', url: 'http://stream-gw:8080/v1/backfill', cred: 'streamGwAuth', timeoutMs: 15000, retries: 3, onError: 'continueRegularOutput',
      body: '={{ JSON.stringify($json.backfill) }}', note: 'Idempotent on feed_id + window.',
    }),
    execWf('Notify DQ', 'AQOS16Notifier00', { wait: false }),
  ],
  connections: [
    ['Gateway events', 'Compute HMAC'],
    ['Compute HMAC', 'Verify signature'],
    ['Verify signature', 'Signature valid?'],
    ['Signature valid?', 'Dead-letter bad request', { out: 'false' }],
    ['Dead-letter bad request', 'Reject 401'],
    ['Signature valid?', 'Ingest event', { out: 'true' }],
    ['Ingest event', 'Acknowledge'],
    ['Ingest event', 'First delivery?'],
    ['First delivery?', 'Route by type', { out: 'true' }],
    ['Route by type', 'Run signal cycle', { out: 'bar_close' }],
    ['Route by type', 'Run risk monitor', { out: 'market_stress' }],
    ['Route by type', 'Run settlement', { out: 'execution_events' }],
    ['Route by type', 'Feed rules', { out: 'feed_status' }],
    ['Route by type', 'Other event stored', { out: 'other' }],
    ['Feed rules', 'Quarantine?'],
    ['Quarantine?', 'Quarantine feed', { out: 'true' }],
    ['Feed rules', 'Needs triage?'],
    ['Needs triage?', 'Build DQ triage request', { out: 'true' }],
    ['Build DQ triage request', 'Claude DQ triage'],
    ['Claude DQ triage', 'DQ triage result'],
    ['DQ triage result', 'Notify DQ'],
    ['DQ triage result', 'Backfill?'],
    ['Backfill?', 'Request backfill', { out: 'true' }],
  ],
});
